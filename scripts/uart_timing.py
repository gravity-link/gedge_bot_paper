#!/usr/bin/env python3
"""Measure command start-phase timing on the REAL motor UART, without motion.

Motivation
----------
The historical 208x figure concerns pulse-train jitter on the STM32 motor
pins. A UART carries only a seven-byte command; the pulses themselves are
generated by MCU GPIO and are not visible on the serial link. This script
therefore measures a different, well-defined quantity: the *host-side command
start phase* over the actual ch341 USB-UART path at 9600 baud. Earlier A/B
runs approximated the same quantity using a POSIX pseudo-terminal.

Zero-motion guarantee (statically checked at runtime)
-----------------------------------------------------
The audited firmware ``ProcessCommand()`` dispatches only CMD 0x01..0x09.
We send ``AA 55 00 00 00 0D 0A``: well-formed framing, CMD=0x00, no switch
case matches, so no motor routine is invoked. The firmware source is parsed
before opening the port; if 0x00 ever appears in its case list, the run is
refused. No physical motion is possible from this frame.

What this does NOT measure
--------------------------
* MCU pulse-train cadence or pulse-width jitter (needs a probe on the motor
  GPIO pins, e.g. a logic analyser at >=10 kHz).
* MCU reception/acknowledgement (the firmware emits no per-command ACK).
* Any effect of AI load on the *pulse train*, only on command emission.
"""
import argparse
import hashlib
import json
import math
import os
import platform
import re
import select
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIRMWARE = ROOT / "evidence" / "motor_uart_vision.current.c"
NOOP_FRAME = bytes([0xAA, 0x55, 0x00, 0x00, 0x00, 0x0D, 0x0A])


def percentile_nearest(values, probability):
    if not values:
        return None
    ordered = sorted(values)
    return ordered[max(0, math.ceil(probability * len(ordered)) - 1)]


def summarize(post_write_ns, period_ms):
    """Identical estimator to scripts/ab_control.py (population stdev, nearest-rank p99)."""
    intervals = [(b - a) / 1e6 for a, b in zip(post_write_ns, post_write_ns[1:])]
    deviations = [v - period_ms for v in intervals]
    absolute = [abs(v) for v in deviations]
    return {
        "interval_count": len(intervals),
        "period_ms": period_ms,
        "interval_mean_ms": statistics.fmean(intervals) if intervals else None,
        "interval_std_ms": statistics.pstdev(intervals) if len(intervals) > 1 else 0.0,
        "interval_p50_ms": percentile_nearest(intervals, 0.50),
        "interval_p99_ms": percentile_nearest(intervals, 0.99),
        "jitter_p99_abs_deviation_ms": percentile_nearest(absolute, 0.99),
        "jitter_max_abs_deviation_ms": max(absolute) if absolute else None,
        "max_interval_ms": max(intervals) if intervals else None,
        "min_interval_ms": min(intervals) if intervals else None,
        "intervals_ms": intervals,
        "signed_deviations_ms": deviations,
    }


def latency_stats(values):
    clean = [float(v) for v in values if v is not None]
    if not clean:
        return {"n": 0}
    return {
        "n": len(clean),
        "mean_ms": statistics.fmean(clean),
        "pstdev_ms": statistics.pstdev(clean) if len(clean) > 1 else 0.0,
        "p50_ms": percentile_nearest(clean, 0.50),
        "p99_ms": percentile_nearest(clean, 0.99),
        "max_ms": max(clean),
    }


def command_output(argv):
    try:
        return subprocess.check_output(argv, stderr=subprocess.STDOUT,
                                       timeout=5, text=True).strip()
    except Exception as exc:
        return "unavailable: %s: %s" % (type(exc).__name__, exc)


def firmware_case_bytes():
    """Parse the audited firmware's ProcessCommand switch cases."""
    if not FIRMWARE.exists():
        return None, "firmware snapshot missing: %s" % FIRMWARE
    text = FIRMWARE.read_text(errors="replace")
    start = text.find("void ProcessCommand")
    if start < 0:
        return None, "ProcessCommand not found in firmware snapshot"
    body = text[start:start + 4000]
    cases = sorted({int(m, 16) for m in re.findall(r"case\s+0x([0-9A-Fa-f]{2})\s*:", body)})
    return cases, None


def assert_noop_is_inert():
    cases, err = firmware_case_bytes()
    if err:
        raise RuntimeError("cannot verify zero-motion guarantee: " + err)
    if 0x00 in cases:
        raise RuntimeError("CMD 0x00 IS DISPATCHED by firmware; refusing to write")
    if not cases:
        raise RuntimeError("no switch cases parsed; refusing to write")
    return cases


def probe_link(device, result):
    """Read-only link inventory; never opens the port for writing."""
    info = {"device": device,
            "exists": os.path.exists(device),
            "usb_bridge": command_output(["lsusb"]),
            "by_id": None,
            "termios_speed": None}
    by_id = Path("/dev/serial/by-id")
    if by_id.exists():
        info["by_id"] = sorted(p.name for p in by_id.iterdir())
    if info["exists"]:
        try:
            import termios
            fd = os.open(device, os.O_RDONLY | os.O_NOCTTY | os.O_NONBLOCK)
            try:
                attrs = termios.tcgetattr(fd)
                info["termios_speed"] = {"ispeed": attrs[4], "ospeed": attrs[5],
                                         "B9600": termios.B9600}
                info["iflag"] = attrs[0]
                info["lflag"] = attrs[3]
            finally:
                os.close(fd)
        except Exception as exc:
            info["termios_error"] = "%s: %s" % (type(exc).__name__, exc)
    info["logic_analyser_tools"] = [
        c for c in ("sigrok-cli", "pulseview", "openocd", "pyocd", "st-util")
        if subprocess.call(["sh", "-c", "command -v %s" % c],
                           stdout=subprocess.DEVNULL,
                           stderr=subprocess.DEVNULL) == 0]
    result["link_inventory"] = info


def configure_raw_9600(fd):
    import termios
    attrs = termios.tcgetattr(fd)
    attrs[0] &= ~(termios.IGNBRK | termios.BRKINT | termios.PARMRK |
                  termios.ISTRIP | termios.INLCR | termios.IGNCR |
                  termios.ICRNL | termios.IXON)
    attrs[1] &= ~termios.OPOST
    attrs[2] &= ~(termios.PARENB | termios.CSIZE | termios.CSTOPB |
                  termios.HUPCL)
    if hasattr(termios, "CRTSCTS"):
        attrs[2] &= ~termios.CRTSCTS
    attrs[2] |= termios.CS8 | termios.CLOCAL | termios.CREAD
    attrs[3] &= ~(termios.ECHO | termios.ECHONL | termios.ICANON |
                  termios.ISIG | termios.IEXTEN)
    attrs[4] = attrs[5] = termios.B9600
    attrs[6][termios.VMIN] = 0
    attrs[6][termios.VTIME] = 0
    termios.tcsetattr(fd, termios.TCSANOW, attrs)
    termios.tcflush(fd, termios.TCIOFLUSH)


def start_load(args):
    """Optionally launch the same YOLO background load used by ab_control.py."""
    if not args.load_python:
        return None, None, None, None
    import shlex
    ready = Path(tempfile.mkstemp(prefix="gedgebot_uart_load_", suffix=".json")[1])
    log_path = Path(args.output).with_suffix(Path(args.output).suffix + ".load.log")
    log = open(log_path, "w")
    loader = Path(args.load_script) if args.load_script else Path(__file__).with_name("yolo_load.py")
    argv = [args.load_python, str(loader), "--model", args.load_model,
            "--imgsz", str(args.load_imgsz), "--ready-file", str(ready)]
    env = os.environ.copy()
    env.update({"HF_HUB_OFFLINE": "1", "TRANSFORMERS_OFFLINE": "1"})
    proc = subprocess.Popen(argv, stdout=log, stderr=subprocess.STDOUT, env=env)
    deadline = time.monotonic() + args.load_timeout
    metadata = None
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            raise RuntimeError("load exited %s; see %s" % (proc.returncode, log_path))
        try:
            candidate = json.loads(ready.read_text())
            if candidate.get("status") == "ready":
                metadata = candidate
                break
        except (OSError, ValueError):
            pass
        time.sleep(0.1)
    else:
        raise TimeoutError("load not ready in %ss" % args.load_timeout)
    time.sleep(args.load_warmup)
    return proc, metadata, log, str(loader.resolve())


def stop_load(proc, log):
    if proc is not None:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait(timeout=5)
    if log is not None:
        log.close()


def run_measurement(args, cases):
    import termios
    fd = os.open(args.device, os.O_RDWR | os.O_NOCTTY)
    scheduled, pre_write, post_write, post_drain = [], [], [], []
    rx_bytes = 0
    load_proc, load_meta, load_log, load_path = start_load(args)
    try:
        configure_raw_9600(fd)
        period_ns = round(args.period_ms * 1e6)
        origin = time.perf_counter_ns() + 100_000_000
        for index in range(args.intervals + 1):
            target = origin + index * period_ns
            while True:
                remaining = (target - time.perf_counter_ns()) / 1e9
                if remaining <= 0:
                    break
                time.sleep(min(remaining, 0.002))
            scheduled.append(target)
            pre = time.perf_counter_ns()
            written = os.write(fd, NOOP_FRAME)
            post = time.perf_counter_ns()
            if written != len(NOOP_FRAME):
                raise RuntimeError("short UART write: %d/%d" % (written, len(NOOP_FRAME)))
            termios.tcdrain(fd)
            drained = time.perf_counter_ns()
            pre_write.append(pre)
            post_write.append(post)
            post_drain.append(drained)
            readable, _, _ = select.select([fd], [], [], 0)
            if readable:
                try:
                    rx_bytes += len(os.read(fd, 256))
                except OSError:
                    pass
    finally:
        os.close(fd)
        stop_load(load_proc, load_log)

    summary = summarize(post_write, args.period_ms)
    drain_after_write_ms = [(d - w) / 1e6 for w, d in zip(post_write, post_drain)]
    return {
        "schema": "gedgebot.uart_timing.real_link.v1",
        "condition": args.condition,
        "timestamp_unix": time.time(),
        "evidence_status": "device_measurement_real_uart_no_motion",
        "device_measurement": True,
        "citation_allowed": False,
        "citation_scope": ("Only as a new 2026-11-07 real-UART command-start-phase "
                           "measurement in a parallel table; never as pulse-train "
                           "jitter, never as an October reproduction, never pooled "
                           "with historical or pty data."),
        "physical_uart_device": args.device,
        "physical_uart_writes": True,
        "physical_motion": False,
        "motion_exclusion_basis": ("Firmware ProcessCommand() dispatches CMD %s; "
                                   "CMD=0x00 has no case, so no motor routine runs. "
                                   "Verified by parsing the audited firmware snapshot."
                                   % ", ".join("0x%02X" % c for c in cases)),
        "frame_hex": NOOP_FRAME.hex(" ").upper(),
        "frame_length_bytes": len(NOOP_FRAME),
        "baud_rate": 9600,
        "raw_mode": "8N1, CLOCAL, HUPCL cleared, tcdrain after each frame",
        "mcu_ack_observed": rx_bytes > 0,
        "mcu_rx_bytes_observed": rx_bytes,
        "mcu_pulse_telemetry": False,
        "logic_analyser": False,
        "frames_sent": len(post_write),
        "scheduled_ns": scheduled,
        "pre_write_ns": pre_write,
        "post_write_ns": post_write,
        "post_drain_ns": post_drain,
        "write_latency_ms": [(b - a) / 1e6 for a, b in zip(pre_write, post_write)],
        "drain_after_write_ms": drain_after_write_ms,
        "write_latency_stats": latency_stats(
            [(b - a) / 1e6 for a, b in zip(pre_write, post_write)]),
        "drain_latency_stats": latency_stats(drain_after_write_ms),
        "summary": summary,
        "yolo_load": load_meta,
        "load_script": load_path,
        "load_returncode": load_proc.returncode if load_proc is not None else None,
        "firmware_snapshot": str(FIRMWARE),
        "firmware_sha256": hashlib.sha256(FIRMWARE.read_bytes()).hexdigest(),
        "platform": platform.platform(),
        "python": sys.version,
        "l4t_release": (Path("/etc/nv_tegra_release").read_text().strip()
                        if Path("/etc/nv_tegra_release").exists() else None),
        "power_mode": (command_output(["nvpmodel", "-q"])
                       if platform.machine() == "aarch64" else "not Jetson"),
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--device", default="/dev/ttyUSB0")
    p.add_argument("--mode", choices=("probe", "no-motion"), default="probe",
                   help="probe is read-only; no-motion writes inert frames to the real UART")
    p.add_argument("--confirm-physical-uart", action="store_true",
                   help="explicit acknowledgement required for --mode no-motion")
    p.add_argument("--condition", default="probe")
    p.add_argument("--intervals", type=int, default=200)
    p.add_argument("--period-ms", type=float, default=50.0)
    p.add_argument("--output", required=True)
    p.add_argument("--load-python")
    p.add_argument("--load-script")
    p.add_argument("--load-model", default="/root/src/sample/yolov8n.pt")
    p.add_argument("--load-imgsz", type=int, default=640)
    p.add_argument("--load-timeout", type=float, default=120.0)
    p.add_argument("--load-warmup", type=float, default=2.0)
    args = p.parse_args()
    if args.intervals < 1 or args.period_ms <= 0:
        p.error("intervals must be positive and period-ms must be > 0")
    if args.mode == "no-motion" and not args.confirm_physical_uart:
        p.error("--mode no-motion requires --confirm-physical-uart; "
                "this writes to a physical serial port")

    cases, case_err = firmware_case_bytes()
    result = {
        "mode": args.mode,
        "firmware_dispatched_cmds": ["0x%02X" % c for c in cases] if cases else [],
        "firmware_case_parse_error": case_err,
        "noop_cmd": "0x00",
        "noop_is_inert": bool(cases) and 0x00 not in cases,
    }
    probe_link(args.device, result)

    if args.mode == "no-motion":
        checked = assert_noop_is_inert()
        result.update(run_measurement(args, checked))
        s = result["summary"]
        print(json.dumps({
            "condition": args.condition,
            "frames": result["frames_sent"],
            "p99_abs_deviation_ms": s["jitter_p99_abs_deviation_ms"],
            "max_abs_deviation_ms": s["jitter_max_abs_deviation_ms"],
            "write_p99_ms": result["write_latency_stats"]["p99_ms"],
            "drain_p99_ms": result["drain_latency_stats"]["p99_ms"],
            "mcu_ack_observed": result["mcu_ack_observed"],
            "physical_motion": result["physical_motion"],
        }, indent=2))
    else:
        print(json.dumps({k: v for k, v in result.items()
                          if k != "link_inventory" or not args.device}, indent=2)[:1200])
        print(json.dumps(result["link_inventory"], indent=2)[:1200])

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=2) + "\n")
    print("output:", out)


if __name__ == "__main__":
    main()
